const translations: Record<Language, Translations> = { en, ru };

let currentLang: Language = 'ru';

export function setLanguage(lang: Language) {
  currentLang = lang;
  try {
    localStorage.setItem('gnozian_language', lang);
  } catch {}
}

export function getLanguage(): Language {
  try {
    const saved = localStorage.getItem('gnozian_language');
    if (saved === 'en' || saved === 'ru') return saved;
  } catch {}
  return currentLang;
}

// Load saved language on init
(() => {
  try {
    const saved = localStorage.getItem('gnozian_language');
    if (saved === 'en' || saved === 'ru') currentLang = saved;
  } catch {}
})();

function getFlatString(
  key: string,
  lang: Language
): string | undefined {
  const table = translations[lang] as Translations;
  if (key in table && typeof (table as Record<string, unknown>)[key] === 'string') {
    return (table as Record<string, string>)[key];
  }
  // Nested (legacy) keys, e.g. a top-level { menu: { newGame: '...' } } shape
  const keys = key.split('.');
  let v: unknown = table;
  for (const k of keys) {
    if (v && typeof v === 'object' && k in (v as object)) v = (v as Translations)[k];
    else {
      v = undefined;
      break;
    }
  }
  if (typeof v === 'string') return v;
  return undefined;
}

function expandParams(
  s: string,
  params?: Record<string, string | number>
): string {
  if (!params) return s;
  return s.replace(/\{(\w+)\}/g, (_, name) => String(params[name] ?? `{${name}}`));
}

/** Keys in `en` / `ru` are flat (e.g. "menu.newGame") — not nested by segment. */
export function t(key: string, params?: Record<string, string | number>): string {
  const primary = getFlatString(key, currentLang);
  if (primary != null) return expandParams(primary, params);

  const enStr = getFlatString(key, 'en');
  if (enStr != null) return expandParams(enStr, params);

  return key;
}

// Hook for React components
export function useI18n() {
  return { t, language: currentLang, setLanguage };
}
